/** Maintainer tool: regenerates src/import/rimworld/core-tables.ts from the
 * game's own definition files (numbers and identifiers only: backstory skill
 * gains and disabled work tags, the human body part order). No text, title or
 * description is copied.
 * node --experimental-transform-types scripts/rws-import-core-tables.ts [CoreDefsDir]
 */
import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {parseXml,child,children,text,type XmlNode} from '../src/import/rimworld/xml.ts';

const defs=resolve(process.argv[2]??'E:/Steam/steamapps/common/RimWorld/Data/Core/Defs');
const SKILLS:Record<string,string>={Shooting:'Sh',Melee:'Me',Construction:'Co',Mining:'Mi',Cooking:'Ck',Plants:'Pl',Animals:'An',Crafting:'Cr',Artistic:'Ar',Medicine:'Md',Social:'So',Intellectual:'In'};
const TAGS:Record<string,string>={ManualDumb:'d',ManualSkilled:'s',Violent:'v',Caring:'c',Social:'o',Commoner:'m',Intellectual:'i',Animals:'a',Artistic:'r',Crafting:'f',Cooking:'k',Firefighting:'x',Cleaning:'l',Hauling:'h',PlantWork:'p',Mining:'n',Hunting:'u',Constructing:'b',Shooting:'t',AllWork:'*'};
const files=(dir:string):string[]=>readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?files(join(dir,e.name)):e.name.endsWith('.xml')?[join(dir,e.name)]:[]);

const backstories:string[]=[];
for(const file of files(join(defs,'BackstoryDefs')).sort()){
 const root=parseXml(readFileSync(file,'utf8'));
 for(const d of children(root,'BackstoryDef')){
  const name=text(d,'defName');if(!name)continue;
  const slot=text(d,'slot')==='Adulthood'?'a':'c';
  const gains=child(d,'skillGains')?.children.map(g=>{const code=SKILLS[g.name];return code?`${code}${Number(g.text.trim())}`:'';}).filter(Boolean).join(',')??'';
  const disables=(text(d,'workDisables')??'').split(',').map(s=>TAGS[s.trim()]??'').join('');
  backstories.push(`${JSON.stringify(name)}:${JSON.stringify(`${slot}|${gains}|${disables}`)}`);
 }
}
// Human body: parts in pre-order, as the game numbers them in saves.
const body=parseXml(readFileSync(join(defs,'Bodies','Bodies_Humanlike.xml'),'utf8'));
const human=children(body,'BodyDef').find(b=>text(b,'defName')==='Human');
if(!human)throw Error('Human body not found');
const parts:string[]=[];
const walk=(node:XmlNode)=>{const label=text(node,'customLabel')??'',side=/^left\b/.test(label)?'left':/^right\b/.test(label)?'right':'';
 const finger=/(pinky|ring finger|middle finger|index finger|thumb|little toe|fourth toe|middle toe|second toe|big toe)$/.exec(label)?.[1]?.replace(' ','-');
 parts.push(`${text(node,'def')}|${side}|${finger??''}`);for(const p of children(child(node,'parts'),'li'))walk(p);};
walk(child(human,'corePart')!);
const out=`/** Generated by scripts/rws-import-core-tables.ts from the game's definition
 * files: identifiers and numbers only (no text). Do not edit by hand. */
/** Backstory → "slot|skill gains|disabled work tags" (slot c/a; skills
 * Sh Me Co Mi Ck Pl An Cr Ar Md So In; tags: d manual-dumb, s manual-skilled,
 * v violent, c caring, o social, m commoner, i intellectual, a animals,
 * r artistic, f crafting, k cooking, x firefighting, l cleaning, h hauling,
 * p plant work, n mining, u hunting, b constructing, t shooting, * all). */
export const CORE_BACKSTORY_EFFECTS:Readonly<Record<string,string>>={${backstories.join(',')}};
/** Human body parts in save order: "def|side|finger or toe". */
export const CORE_HUMAN_BODY_PARTS:readonly string[]=${JSON.stringify(parts)};
`;
writeFileSync(resolve('src/import/rimworld/core-tables.ts'),out);
console.log(JSON.stringify({backstories:backstories.length,bodyParts:parts.length}));
