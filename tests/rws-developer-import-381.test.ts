test('only the exact original Core-placed records are admitted, without changing tiles or research, and both save and Full preserve them',()=>{
 const {w,index,conversion,battery}=prepared(),originalResearch=structuredClone(w.research),originalTiles=JSON.stringify(w.tiles);
 expect(validateWorld(w)).not.toEqual([]);
 const p=captureDeveloperImport381(conversion);
 expect(p.floors).toEqual([{index,terrain:'soft-sand',floor:'ancient-concrete'}]);
 expect(p.buildings.find(row=>row.id===battery.id)?.research).toBe('batteries');
 expect(w.research).toEqual(originalResearch);
 expect(JSON.stringify(w.tiles)).toBe(originalTiles);
 expect(researchUnlocked(w,'batteries')).toBe(false);
 expect(validateWorld(w)).toEqual([]);
 const raw=serializeWorld(w),copy=deserializeWorld(raw);
 expect(serializeWorld(copy)).toBe(raw);
 expect(new SnapshotDecoder().adopt(structuredClone(new SnapshotEncoder().encode(copy,0,0,true))).status).toBe('applied');
 const decoder=new SnapshotDecoder(),encoder=new SnapshotEncoder();
 expect(decoder.adopt(structuredClone(encoder.encode(copy,0,0,true))).status).toBe('applied');
 expect(decoder.adopt(structuredClone(encoder.encode(copy,0,0,false))).status).toBe('applied');
 expect(applyCommand(copy,{type:'designate',kind:'battery',x:20,z:20,orientation:0,material:'steel'}).ok).toBe(false);
 const installed=copy.structures.find(s=>s.id===battery.id)!;
 expect(developerResearchPlacement381(copy,installed)).toBe(true);
 expect(developerResearchPlacement381(copy,{...installed})).toBe(false);
 const replaced={...installed,id:copy.nextId++};
 copy.structures=copy.structures.map(s=>s===installed?replaced:s);
 expect(developerResearchPlacement381(copy,replaced)).toBe(false);
 expect(validateWorld(copy)).not.toEqual([]);
});

