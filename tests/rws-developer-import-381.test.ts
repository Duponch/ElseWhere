 expect(productionResearchUnlocked(copy,bill.recipe)).toBe(false);
 expect(validateWorld(copy)).toEqual([]);
 expect(dec.adopt(structuredClone(enc.encode(copy,0,1,false))).status).toBe('applied');
 // Same recipe on a copied bill with a fresh id, or same original bill on
 // a different station, has no provenance. Shape and global ID guards stay.
 const duplicated=deserializeWorld(original),dupStation=duplicated.structures.find(s=>s.id===first.id)!;
 dupStation.bills!.push({...dupStation.bills![0]!,id:duplicated.nextId++});
 expect(validateWorld(duplicated)).not.toEqual([]);
 expect(new SnapshotDecoder().adopt(structuredClone(new SnapshotEncoder().encode(duplicated,0,0,true))).status).toBe('resync');
 const moved=deserializeWorld(original),from=moved.structures.find(s=>s.id===first.id)!,to=moved.structures.find(s=>s.id===second.id)!;
 to.bills!.push(from.bills!.shift()!);
 expect(validateWorld(moved)).not.toEqual([]);
 const badRecipe=deserializeWorld(original),witness=badRecipe.developerPlacements381!.bills![0]!;
 witness.recipe='make-pemmican';
 expect(validateWorld(badRecipe)).not.toEqual([]);
 const noMarker=deserializeWorld(original);delete noMarker.developerTest381;delete noMarker.developerPlacements381;
 expect(validateWorld(noMarker)).not.toEqual([]);
 copy.research??={points:0,project:null};
 copy.research.packagedSurvivalMeals={points:researchCost('packaged-survival-meals'),completedAt:copy.tick};
 expect(productionResearchUnlocked(copy,bill.recipe)).toBe(true);
 expect(applyCommand(copy,{type:'bill-add',structureId:second.id,recipe:'cook-survival-meal'}).ok).toBe(true);
